from typing import Protocol
from ..domain.order import Order


class OrderRepository(Protocol):
    async def create(self, order: Order) -> Order: ...
    async def get_by_id(self, order_id: int) -> Order | None: ...
    async def list_by_customer(self, customer_id: int) -> list[Order]: ...
    async def update_status(self, order_id: int, status: str) -> None: ...
    async def customer_exists(self, customer_id: int) -> bool: ...


class EventPublisher(Protocol):
    """Запись в outbox внутри той же транзакции (требование 8)."""
    async def enqueue(self, event_type: str, payload: dict) -> None: ...


class InboxRepository(Protocol):
    async def is_processed(self, event_id: str) -> bool: ...
    async def mark_processed(self, event_id: str, event_type: str) -> None: ...


class CatalogClient(Protocol):
    """
    Порт синхронного обращения к Catalog (реализуется gRPC-клиентом,
    требование 10). Возвращает {book_id: price} для существующих книг.
    """
    async def get_prices(self, book_ids: list[int]) -> dict[int, int]: ...

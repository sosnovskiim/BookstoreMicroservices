from typing import Protocol
from ..domain.stock import StockItem
from ..domain.purchase import Purchase


class StockRepository(Protocol):
    async def get(self, book_id: int) -> StockItem | None: ...
    async def list_all(self) -> list[StockItem]: ...
    async def save(self, item: StockItem) -> StockItem: ...
    async def top_up(self, book_id: int, amount: int) -> StockItem | None: ...


class PurchaseRepository(Protocol):
    async def create(self, purchase: Purchase) -> Purchase: ...


class EventPublisher(Protocol):
    """Публикация события в outbox (внутри той же транзакции)."""
    async def enqueue(self, event_type: str, payload: dict) -> None: ...


class InboxRepository(Protocol):
    """Идемпотентность: проверка/запись обработанных event_id (требование 8)."""
    async def is_processed(self, event_id: str) -> bool: ...
    async def mark_processed(self, event_id: str, event_type: str) -> None: ...
